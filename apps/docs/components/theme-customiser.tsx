"use client"

/**
 * The theme customiser's controls: build a palette and watch the site take it.
 *
 * Two levels, because there are two kinds of question.
 *
 * **Basic** is three choices — a brand colour, a neutral, and how round the
 * corners are. That is most of what gives a site its look, and it is as much
 * as anyone wants to decide before they have seen it. The nineteen tokens are
 * generated from the first two by `lib/theme-generator.ts`, which is also what
 * produced the default theme, and which does not emit a pair that fails
 * contrast. So this level cannot be got wrong.
 *
 * **Advanced** is every token, behind a disclosure. Each gets two rows: a
 * swatch, its name and its hex on the first, and the three OKLCH channels on
 * the second. Both edit the same colour. Hex is how a brand colour arrives —
 * pasted from a brand guide — and OKLCH is how it gets fixed, because
 * lightness is the axis contrast actually depends on, so moving L changes the
 * ratio predictably where nudging a hex is guesswork. This level *can* be got
 * wrong, which is what the contrast badge is for: it scores the palette
 * against the **same pairs and the same thresholds** that
 * `scripts/check-contrast.ts` enforces in CI, from `lib/theme-tokens.ts`.
 *
 * Every edit goes through `commit`, which stores the whole theme and switches
 * the site to the `custom` preset. There is no local draft: the docs site
 * itself — chrome, sections and preview iframes — is the preview, so an edit
 * that only moved component state would be a control that does nothing. The
 * panel this renders in keeps its own colours pinned to the shipped palette,
 * because editing a broken theme must not break the tool you are using to fix
 * it.
 *
 * a11y of the tool itself:
 *
 *  - The basic choices are radio groups with a visible legend, so each
 *    announces what it is, which option is current, and moves with the arrow
 *    keys. A colour swatch is named for its family, and the current one is
 *    marked by a ring — a shape, not a second colour.
 *  - A swatch is painted in the primary that family would actually give you,
 *    not in its prettiest step. That is the more honest picture, and it is
 *    also the one guaranteed to clear 3:1 against the panel (WCAG 1.4.11).
 *  - Every advanced field is named for its token and what it edits ("Primary
 *    lightness", "Primary hex"), so sixty-odd inputs are told apart without
 *    seeing the swatch beside them.
 *  - The failing pairs are listed as text, never signalled by colour alone.
 */

import { ChevronDownIcon, RotateCcwIcon } from "lucide-react"
import { useId, useMemo, useState } from "react"

// Generated by `scripts/extract-palettes.ts`, which the docs `registry` task
// runs. turbo.json makes typecheck, test and build depend on that task, because
// this is a static import and the file is gitignored.
import palettes from "@/.generated/palettes.json"
import {
  DEFAULT_RADIUS,
  RADII,
  customThemeCss,
  useCustomTheme,
  type CustomTheme,
  type Radius,
} from "@/lib/custom-theme"
import {
  contrastRatio,
  formatOklch,
  fromHex,
  parseOklch,
  toHex,
  type Oklch,
} from "@/lib/oklch"
import {
  BRAND_FAMILIES,
  DEFAULT_RECIPE,
  NEUTRAL_FAMILIES,
  brandColour,
  generateTheme,
  type Recipe,
} from "@/lib/theme-generator"
import {
  EDITABLE_TOKENS,
  checkPalette,
  type Palette,
  type TokenName,
} from "@/lib/theme-tokens"
import {
  DEFAULT_PRESET,
  SHIPPED_PRESETS,
  useActivePreset,
  useResolvedMode,
  type ShippedPreset,
} from "./theme-switcher"
import { CopyButton } from "./copy-button"
import { Badge } from "@registry/ui/badge"
import { Button } from "@registry/ui/button"
import { cn } from "@registry/lib/utils"

const shipped = palettes as Record<string, Palette>

/**
 * A shipped preset as a starting point. The default carries its recipe,
 * because it *is* one — `theme-generator.test.ts` checks that generating
 * `DEFAULT_RECIPE` reproduces the shipped palette exactly.
 */
const seedFrom = (preset: ShippedPreset): CustomTheme => ({
  light: { ...shipped[`${preset}-light`]! },
  dark: { ...shipped[`${preset}-dark`]! },
  ...(preset === DEFAULT_PRESET ? { recipe: DEFAULT_RECIPE } : {}),
})

/** Human labels, so the fields do not read as raw custom property names. */
const TOKEN_LABELS: Record<TokenName, string> = {
  "--background": "Background",
  "--foreground": "Foreground",
  "--card": "Card",
  "--card-foreground": "Card foreground",
  "--popover": "Popover",
  "--popover-foreground": "Popover foreground",
  "--primary": "Primary",
  "--primary-foreground": "Primary foreground",
  "--secondary": "Secondary",
  "--secondary-foreground": "Secondary foreground",
  "--muted": "Muted",
  "--muted-foreground": "Muted foreground",
  "--accent": "Accent",
  "--accent-foreground": "Accent foreground",
  "--destructive": "Destructive",
  "--destructive-foreground": "Destructive foreground",
  "--border": "Border",
  "--input": "Input border",
  "--ring": "Focus ring",
}

const CHANNELS = [
  { key: "l", label: "L", name: "lightness", min: 0, max: 1, step: 0.005, places: 3 },
  { key: "c", label: "C", name: "chroma", min: 0, max: 0.37, step: 0.002, places: 3 },
  { key: "h", label: "H", name: "hue", min: 0, max: 360, step: 0.1, places: 1 },
] as const

const FOCUS_WITHIN = "has-[:focus-visible]:ring-ring has-[:focus-visible]:ring-2"

interface DraftFieldProps extends React.ComponentPropsWithoutRef<"input"> {
  /** The canonical text, shown whenever the field is not mid-edit. */
  value: string
  /** Called with the raw text; ignore anything that does not parse yet. */
  onCommit: (raw: string) => void
}

/**
 * An input that keeps what you typed until it parses.
 *
 * Half a hex code is not a colour, and neither is "0." — but both have to stay
 * on screen while you finish typing them. So the field holds its own draft, the
 * palette keeps the last value that parsed, and blurring throws an unfinished
 * draft away rather than leaving the field disagreeing with the swatch.
 */
function DraftField({ value, onCommit, className, ...props }: DraftFieldProps) {
  const [draft, setDraft] = useState<string | null>(null)

  return (
    <input
      {...props}
      value={draft ?? value}
      onChange={(event) => {
        setDraft(event.target.value)
        onCommit(event.target.value)
      }}
      onBlur={() => setDraft(null)}
      className={cn(
        "border-input bg-background focus-visible:ring-ring h-7 rounded-md border px-1.5 font-mono text-xs tabular-nums focus-visible:outline-none focus-visible:ring-2",
        className,
      )}
    />
  )
}

interface SegmentedProps<T extends string> {
  legend: string
  name: string
  value: T | undefined
  options: readonly { value: T; label: string }[]
  onChange: (next: T) => void
}

/** A radio group drawn as one row of segments, the way the header's mode switch is. */
function Segmented<T extends string>({
  legend,
  name,
  value,
  options,
  onChange,
}: SegmentedProps<T>) {
  return (
    <fieldset>
      <legend className="mb-2 text-sm font-medium">{legend}</legend>
      <div className="border-border flex gap-0.5 rounded-lg border p-0.5">
        {options.map((option) => (
          <label
            key={option.value}
            className={cn(
              "flex h-8 flex-1 cursor-pointer items-center justify-center rounded-md text-xs transition-colors",
              FOCUS_WITHIN,
              value === option.value
                ? "bg-secondary text-secondary-foreground font-medium"
                : "text-muted-foreground hover:text-foreground",
            )}
          >
            <input
              type="radio"
              name={name}
              value={option.value}
              checked={value === option.value}
              onChange={() => onChange(option.value)}
              className="sr-only"
            />
            {option.label}
          </label>
        ))}
      </div>
    </fieldset>
  )
}

const capitalise = (word: string): string => word.charAt(0).toUpperCase() + word.slice(1)

const NEUTRAL_OPTIONS = NEUTRAL_FAMILIES.map((family) => ({
  value: family,
  label: capitalise(family),
}))

export function ThemeCustomiser() {
  const [stored, setStored] = useCustomTheme()
  const [preset, setPreset] = useActivePreset()
  const mode = useResolvedMode()
  const [advanced, setAdvanced] = useState(false)
  const id = useId()

  // Until something is stored, the starting point is whatever the site is
  // already showing, so the first change moves the palette in front of you.
  const theme =
    stored ?? seedFrom(preset === "custom" ? DEFAULT_PRESET : (preset as ShippedPreset))
  const palette = theme[mode]
  const { recipe } = theme

  /**
   * The one write path. Storing the theme and selecting the preset together is
   * what makes every control — a swatch, a field, a reseed — change the page
   * at once.
   */
  const commit = (next: CustomTheme) => {
    setStored(next)
    if (preset !== "custom") setPreset("custom")
  }

  /** Basic mode: regenerate both palettes from the two choices. */
  const applyRecipe = (next: Recipe) => {
    const generated = generateTheme(next)
    if (generated) commit({ ...generated, radius: theme.radius, recipe: next })
  }

  /** Advanced mode: one token, in the mode on screen. The recipe no longer holds. */
  const setToken = (token: TokenName, colour: Oklch) => {
    commit({
      light: theme.light,
      dark: theme.dark,
      radius: theme.radius,
      [mode]: { ...palette, [token]: formatOklch(colour) },
    })
  }

  // A palette that did not come from a recipe still has a brand colour to show
  // and to carry into the next choice: its primary. So picking a neutral for
  // the warm preset keeps warm's brown rather than snapping to orange.
  const primary = parseOklch(theme.light["--primary"])
  const brand = recipe?.brand ?? (primary ? toHex({ ...primary, a: 1 }) : "orange")
  const neutral = recipe?.neutral ?? DEFAULT_RECIPE.neutral
  const brandBase = brandColour(brand)
  const brandHex = brandBase ? toHex(brandBase) : "#000000"

  // What each family's primary would be with the current neutral, in the mode
  // on screen — see the header for why the swatches are painted in these.
  const swatches = useMemo(
    () =>
      BRAND_FAMILIES.map((family) => ({
        family,
        colour: generateTheme({ brand: family, neutral })?.[mode]["--primary"],
      })),
    [neutral, mode],
  )

  const checks = useMemo(() => checkPalette(palette, contrastRatio), [palette])
  const failures = checks.filter((check) => !check.passes)
  const css = useMemo(() => customThemeCss(theme), [theme])

  return (
    <div className="flex flex-col gap-5">
      <fieldset>
        <legend className="mb-2 text-sm font-medium">Brand colour</legend>
        <div className="grid grid-cols-9 gap-1.5">
          {swatches.map(({ family, colour }) => (
            <label
              key={family}
              title={capitalise(family)}
              className={cn(
                "ring-offset-background flex aspect-square cursor-pointer rounded-full ring-offset-2",
                FOCUS_WITHIN,
                recipe?.brand === family &&
                  "ring-foreground has-[:focus-visible]:ring-foreground ring-2",
              )}
              style={{ background: colour }}
            >
              <input
                type="radio"
                name={`${id}-brand`}
                value={family}
                checked={recipe?.brand === family}
                onChange={() => applyRecipe({ brand: family, neutral })}
                aria-label={capitalise(family)}
                className="sr-only"
              />
            </label>
          ))}
        </div>
        <div className="mt-3 flex items-center gap-2">
          <label htmlFor={`${id}-brand-hex`} className="text-muted-foreground text-xs">
            Custom
          </label>
          {/* The native picker, for choosing by eye. It reports `#rrggbb`. */}
          <input
            type="color"
            aria-label="Custom colour picker"
            value={brandHex.slice(0, 7)}
            onChange={(event) => applyRecipe({ brand: event.target.value, neutral })}
            className="border-input focus-visible:ring-ring ml-auto size-7 shrink-0 cursor-pointer rounded-md border bg-transparent p-0.5 focus-visible:outline-none focus-visible:ring-2"
          />
          <DraftField
            id={`${id}-brand-hex`}
            value={brandHex}
            onCommit={(raw) => {
              const next = fromHex(raw)
              // A brand is opaque: `toHex` of it is the six-digit form.
              if (next) applyRecipe({ brand: toHex({ ...next, a: 1 }), neutral })
            }}
            spellCheck={false}
            autoCapitalize="none"
            autoCorrect="off"
            maxLength={7}
            className="w-20 text-right"
          />
        </div>
      </fieldset>

      <Segmented
        legend="Neutral"
        name={`${id}-neutral`}
        value={recipe?.neutral}
        options={NEUTRAL_OPTIONS}
        onChange={(next) => applyRecipe({ brand, neutral: next })}
      />

      <Segmented<Radius>
        legend="Corners"
        name={`${id}-radius`}
        value={theme.radius ?? DEFAULT_RADIUS}
        options={RADII}
        onChange={(radius) => commit({ ...theme, radius })}
      />

      <div className="flex flex-col gap-2">
        <Badge variant={failures.length ? "destructive" : "default"} size="sm">
          {failures.length === 0
            ? "All contrast checks pass"
            : `${failures.length} contrast ${failures.length === 1 ? "check fails" : "checks fail"}`}
        </Badge>
        {failures.length > 0 ? (
          <ul className="text-muted-foreground flex flex-col gap-1 text-xs">
            {failures.map((check) => (
              <li key={`${check.fg}-${check.bg}`} className="flex justify-between gap-2">
                <span>{check.label}</span>
                <span className="shrink-0 font-mono">
                  {check.ratio.toFixed(2)}:1 <span aria-hidden>·</span>{" "}
                  <span className="sr-only">needs </span>min {check.min}
                </span>
              </li>
            ))}
          </ul>
        ) : null}
      </div>

      <div className="border-border border-t pt-2">
        <button
          type="button"
          aria-expanded={advanced}
          aria-controls={`${id}-advanced`}
          onClick={() => setAdvanced((open) => !open)}
          className="focus-visible:ring-ring flex h-11 w-full items-center justify-between gap-2 rounded-md text-sm font-medium focus-visible:outline-none focus-visible:ring-2"
        >
          Advanced
          <span className="text-muted-foreground flex items-center gap-1.5 text-xs font-normal">
            every colour token
            <ChevronDownIcon
              aria-hidden
              className={cn(
                "duration-facade-fast ease-facade-out size-4 transition-transform",
                advanced && "rotate-180",
              )}
            />
          </span>
        </button>

        <div
          id={`${id}-advanced`}
          hidden={!advanced}
          className={cn("flex-col gap-5 pt-3", advanced && "flex")}
        >
          <div className="flex flex-col gap-2">
            <span id={`${id}-seed`} className="text-sm font-medium">
              Start from
            </span>
            <div
              role="group"
              aria-labelledby={`${id}-seed`}
              className="grid grid-cols-2 gap-1.5"
            >
              {SHIPPED_PRESETS.map((value) => (
                <Button
                  key={value}
                  variant="outline"
                  size="sm"
                  className="capitalize"
                  onClick={() => commit({ ...seedFrom(value), radius: theme.radius })}
                >
                  {value === preset ? (
                    <RotateCcwIcon aria-hidden className="size-3.5" />
                  ) : null}
                  {value}
                </Button>
              ))}
            </div>
          </div>

          <section aria-labelledby={`${id}-tokens`} className="flex flex-col gap-4">
            <h3 id={`${id}-tokens`} className="text-sm font-medium">
              Editing the {mode} palette
            </h3>
            <ul className="flex flex-col gap-4">
              {EDITABLE_TOKENS.map((token) => {
                const colour = parseOklch(palette[token])
                if (!colour) return null
                const label = TOKEN_LABELS[token]
                return (
                  <li key={token} className="flex flex-col gap-1.5">
                    <span className="flex items-center gap-2">
                      <span
                        aria-hidden
                        className="border-border size-5 shrink-0 rounded-md border"
                        style={{ background: palette[token] }}
                      />
                      <span className="text-foreground text-sm font-medium">{label}</span>
                      <DraftField
                        aria-label={`${label} hex`}
                        value={toHex(colour)}
                        onCommit={(raw) => {
                          const next = fromHex(raw)
                          // Alpha comes from the token unless the hex carries its
                          // own, so editing a translucent border stays translucent.
                          if (next) {
                            setToken(
                              token,
                              raw.trim().replace("#", "").length === 8 ||
                                raw.trim().replace("#", "").length === 4
                                ? next
                                : { ...next, a: colour.a },
                            )
                          }
                        }}
                        spellCheck={false}
                        autoCapitalize="none"
                        autoCorrect="off"
                        maxLength={9}
                        className="ml-auto w-24 text-right"
                      />
                    </span>
                    <span className="grid grid-cols-3 gap-1.5">
                      {CHANNELS.map((channel) => (
                        <span key={channel.key} className="flex items-center gap-1">
                          {/* The name comes from aria-label, so this stays a visual
                              cue only and cannot double up with it. */}
                          <span
                            aria-hidden
                            className="text-muted-foreground w-2.5 shrink-0 text-xs font-medium"
                          >
                            {channel.label}
                          </span>
                          <DraftField
                            type="number"
                            aria-label={`${label} ${channel.name}`}
                            value={String(
                              Number(colour[channel.key].toFixed(channel.places)),
                            )}
                            min={channel.min}
                            max={channel.max}
                            step={channel.step}
                            onCommit={(raw) => {
                              const next = Number(raw)
                              if (raw.trim() !== "" && Number.isFinite(next)) {
                                setToken(token, { ...colour, [channel.key]: next })
                              }
                            }}
                            className="w-full"
                          />
                        </span>
                      ))}
                    </span>
                  </li>
                )
              })}
            </ul>
          </section>
        </div>
      </div>

      <div className="border-border flex flex-col items-start gap-2 border-t pt-4">
        <div className="flex w-full items-center justify-between gap-2">
          <CopyButton value={css} label="Copy CSS" />
          {/* Only once there is something to undo: the default needs no reset. */}
          {stored ? (
            <Button
              variant="ghost"
              size="sm"
              className="h-8 px-2.5 text-xs"
              onClick={() => {
                setStored(null)
                setPreset(DEFAULT_PRESET)
              }}
            >
              <RotateCcwIcon aria-hidden className="size-3.5" />
              Reset
            </Button>
          ) : null}
        </div>
        <a
          href="/docs/customise"
          className="text-muted-foreground hover:text-foreground focus-visible:ring-ring rounded-md text-xs underline underline-offset-4 focus-visible:outline-none focus-visible:ring-2"
        >
          Contrast table and how to install it
        </a>
      </div>
    </div>
  )
}
